import numpy as np
import pandas as pd
from pandas.api.types import CategoricalDtype

"""#### **Convert data**"""

# Convert data

def convert_categorical(data, features):
  '''
  Convert nominal features into categories.
  data: DataFrame
  features: List of nominal features
  '''

  for feature in features:
    data[feature] = data[feature].astype('category')

  return data

def convert_ordinal(data, feature_dict):
  '''
  Convert ordinal features into categories.
  data: DataFrame
  feature_dict: Dictionary of ordinal features and categories
                {'feature': ['sub-category1', 'sub-category2']}
  '''

  for feature, subcategories in feature_dict.items():
    if data[feature].dtype.name == 'category':
      continue
    ordinal = CategoricalDtype(categories = subcategories, ordered = True)
    data[feature] = data[feature].astype(ordinal)

  return data

"""#### **Group data**"""

def mean_data(data, feature, target):
  '''
  Calculate the mean data based on groupby variable and variable of interest.
  data: Dataframe
  feature: str groupby variable
  target: str variable of interest
  '''

  df = (data
        .groupby(feature, observed = False)[target]
        .mean()
        .reset_index())

  return df

